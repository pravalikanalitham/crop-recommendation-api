from fastapi import FastAPI
from pydantic import BaseModel, Field
import pandas as pd
import joblib

app = FastAPI(
    title="Customer Churn Prediction API",
    description="Predict customer churn using KNN",
    version="1.0"
)


model = joblib.load("crop_model.pkl")


class CustomerInput(BaseModel):
    tenure: int = Field(ge=0, le=100)
    monthly_charges: float = Field(ge=0)
    total_charges: float = Field(ge=0)
    contract: str


@app.get("/")
def home():
    return {
        "message": "Customer Churn API is running",
        "documentation": "/docs"
    }


@app.get("/health")
def health():
    return {"status": "running"}


@app.post("/predict")
def predict_churn(customer: CustomerInput):

    customer_data = pd.DataFrame([{
        "tenure": customer.tenure,
        "monthly_charges": customer.monthly_charges,
        "total_charges": customer.total_charges,
        "contract": customer.contract
    }])

    prediction = int(model.predict(customer_data)[0])

    probabilities = model.predict_proba(customer_data)[0]
    classes = list(model.classes_)

    churn_probability = float(
        probabilities[classes.index(1)]
    )

    return {
        "predicted_churn": prediction,
        "result": "Churn" if prediction == 1 else "No Churn",
        "churn_probability_percent": round(
            churn_probability * 100, 2
        )
    }
